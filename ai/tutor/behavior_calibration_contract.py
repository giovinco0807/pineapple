"""Fail-closed raw-decision contract for M3 behavior calibration.

The records defined here are deliberately *not* calibration evidence.  They
bind an observed T1/T2 action to the exact public/private information available
to the actor, while keeping root commitments, worker seeds, and any full hidden
trace outside the policy input.  Every derived action field is regenerated by
the verifier from :class:`BehaviorInfoSet` and the canonical action engine.

Passing this verifier only means that raw logging is internally consistent.
Both records and manifests remain ``promotion_eligible=false`` until a separate
locked-test calibration gate is implemented and passed.
"""
